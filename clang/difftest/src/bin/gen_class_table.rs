//! Generate `../src/ffz_class_table.c`: the exact non-ASCII character
//! classification used by the matcher, reproducing nucleo's
//! `char_class_non_ascii` (which is pub(crate), so we re-derive it here using
//! the same std predicates + nucleo's own `is_upper_case`).
//!
//! Output is a breakpoint table: a sorted list of (codepoint, class) where the
//! class holds until the next breakpoint. Built from the SAME rustc/Unicode
//! version that compiles nucleo here, so classification is byte-identical by
//! construction.
use std::fs;
use std::io::Write;

use nucleo_matcher::chars::is_upper_case;

// Must match the ffz_char_class enum values in ffz.h.
const WHITESPACE: u8 = 0;
const NONWORD: u8 = 1;
// DELIMITER = 2 is ASCII-only (config-driven), never produced here.
const LOWER: u8 = 3;
const UPPER: u8 = 4;
const LETTER: u8 = 5;
const NUMBER: u8 = 6;

fn class_of(c: char) -> u8 {
    if c.is_lowercase() {
        LOWER
    } else if is_upper_case(c) {
        UPPER
    } else if c.is_numeric() {
        NUMBER
    } else if c.is_alphabetic() {
        LETTER
    } else if c.is_whitespace() {
        WHITESPACE
    } else {
        NONWORD
    }
}

fn main() {
    let mut runs: Vec<(u32, u8)> = Vec::new();
    let mut prev = 255u8;
    for cp in 0x80u32..=0x10FFFF {
        // Surrogates aren't scalar values and never appear as decoded
        // codepoints (UTF-8 decode maps them to U+FFFD), so skip them without
        // disturbing the run currently in effect.
        if (0xD800..=0xDFFF).contains(&cp) {
            continue;
        }
        let c = class_of(char::from_u32(cp).unwrap());
        if c != prev {
            runs.push((cp, c));
            prev = c;
        }
    }

    // Delta-varint + checkpoint encoding. Each entry encodes
    // (delta_start << 3) | class as LEB128, where delta_start = start - prev.
    // Every K entries a checkpoint stores (absolute start, byte offset) so the
    // C side can binary-search to a block then linearly decode <= K entries.
    const K: usize = 16;
    let mut data: Vec<u8> = Vec::new();
    let mut ckpt: Vec<(u32, u32)> = Vec::new();  // (start, byte offset of this entry)
    let mut prev = 0u32;
    for (i, (start, cls)) in runs.iter().enumerate() {
        if i % K == 0 {
            ckpt.push((*start, data.len() as u32));
        }
        let delta = start - prev;
        prev = *start;
        let mut v = (delta << 3) | (*cls as u32);
        loop {
            let b = (v & 0x7F) as u8;
            v >>= 7;
            if v != 0 {
                data.push(b | 0x80);
            } else {
                data.push(b);
                break;
            }
        }
    }

    let mut s = String::new();
    s.push_str(
        "// AUTO-GENERATED by difftest gen_class_table — DO NOT EDIT.\n\
         // Exact non-ASCII char classification (reproduces nucleo's\n\
         // char_class_non_ascii). Delta-varint stream of (delta_start<<3)|class\n\
         // with periodic checkpoints for binary search.\n\
         #include \"ffz_class.h\"\n\n\
         #ifndef FFZ_COMPACT_CLASS\n",
    );
    s.push_str(&format!("const unsigned ffz_class_ckpt_stride = {K};\n\n"));
    // data bytes
    s.push_str("const uint8_t ffz_class_data[] = {\n");
    let mut line = String::from("    ");
    for b in &data {
        let cell = format!("{}, ", b);
        if line.len() + cell.len() > 96 {
            s.push_str(line.trim_end());
            s.push('\n');
            line = String::from("    ");
        }
        line.push_str(&cell);
    }
    if !line.trim().is_empty() {
        s.push_str(line.trim_end());
        s.push('\n');
    }
    s.push_str("};\nconst size_t ffz_class_data_len = sizeof(ffz_class_data);\n\n");
    // checkpoints
    s.push_str("const ffz_class_ckpt ffz_class_ckpts[] = {\n");
    let mut line = String::from("    ");
    for (start, off) in &ckpt {
        let cell = format!("{{0x{:X},{}}}, ", start, off);
        if line.len() + cell.len() > 96 {
            s.push_str(line.trim_end());
            s.push('\n');
            line = String::from("    ");
        }
        line.push_str(&cell);
    }
    if !line.trim().is_empty() {
        s.push_str(line.trim_end());
        s.push('\n');
    }
    s.push_str(
        "};\nconst size_t ffz_class_ckpts_len = \
         sizeof(ffz_class_ckpts)/sizeof(ffz_class_ckpts[0]);\n\
         #endif  // FFZ_COMPACT_CLASS\n",
    );

    let out = std::env::args().nth(1).unwrap_or_else(|| "../src/ffz_class_table.c".into());
    let mut f = fs::File::create(&out).unwrap();
    f.write_all(s.as_bytes()).unwrap();
    eprintln!(
        "class: {} runs -> data {:.1} KB + {} checkpoints {:.1} KB = {:.1} KB",
        runs.len(),
        data.len() as f64 / 1024.0,
        ckpt.len(),
        ckpt.len() as f64 * 8.0 / 1024.0,
        (data.len() + ckpt.len() * 8) as f64 / 1024.0
    );
}
